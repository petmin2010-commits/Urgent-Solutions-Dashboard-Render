const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname,'public/app.js'),'utf8');
const extracted = source.match(/function kpi\(label,value,note='',cls=''\)\{[\s\S]*?\n\}/);
assert(extracted, 'kpi renderer present');
const kpi = new Function('esc',extracted[0] + ';return kpi;')(v=>String(v));
const ratio = kpi('التغطية المطابقة',89.5,'% وفق نطاق المالك والمقاول');
assert(ratio.includes('89.5%'), 'percentage suffix adjacent to number');
assert(!ratio.includes('89.5%%'), 'no duplicate percent');
assert(ratio.includes('وفق نطاق المالك'), 'explanation preserved');
assert(!ratio.includes('<small>%'), 'stray percent removed from note');
assert(kpi('المشاريع',72).includes('>72</strong>'), 'counts unchanged');
assert(kpi('نسبة التغطية','89.5%').includes('>89.5%</strong>'), 'already formatted unchanged');
assert(kpi('نسبة التغطية',0).includes('>0%</strong>'), 'zero percent shown');
const formatter = fs.readFileSync(path.join(__dirname,'public/percentage-display.js'),'utf8');
assert(formatter.includes('formatTable(table)'), 'tabular percentage formatter installed');
assert(formatter.includes('NUMBER.test(value)'), 'non-numeric values left unchanged');
const html = fs.readFileSync(path.join(__dirname,'public/index.html'),'utf8');
assert(html.includes('percentage-display.js?v='), 'global formatter included in dashboard');
console.log('PASS: percentage card formatting, dedupe, counts, zero, table module, script inclusion');
